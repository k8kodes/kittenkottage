def to_records(weights):
    return [{"date": d, "oz": w} for d, w in weights]

def build():
    out = []
    for b in BATCHES:
        batch = {
            "id": b["id"],
            "label": b["label"],
            "arrival": b["arrival"],
            "notes": b["notes"],
            "mom": None,
            "kittens": [],
        }
        if b["mom"]:
            batch["mom"] = {"name": b["mom"]["name"], "weights": to_records(b["mom"]["weights"])}
        for k in b["kittens"]:
            batch["kittens"].append({
                "name": k["name"],
                "sex": k.get("sex"),
                "color": k.get("color"),
                "weights": to_records(k["weights"]),
            })
        out.append(batch)
    return out

def sanity_check(data):
    print("=== Sanity check: day-over-day jumps > 30% ===")
    for b in data:
        series = list(b["kittens"])
        if b["mom"]:
            series = series + [{"name": b["mom"]["name"] + " (mom)", "weights": b["mom"]["weights"]}]
        for k in series:
            prev = None
            for w in k["weights"]:
                if prev is not None and prev > 0:
                    change = abs(w["oz"] - prev) / prev
                    if change > 0.3:
                        print(f"  {b['label']} / {k['name']}: {w['date']} {w['oz']}oz (prev {prev}oz, {change:.0%} change)")
                prev = w["oz"]

